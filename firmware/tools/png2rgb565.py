#!/usr/bin/env python3
"""Convert the boot logo PNG into a 240x240 RGB565 array for the sketch.

    python3 firmware/tools/png2rgb565.py firmware/assets/boot_logo.png

Writes firmware/O2_Analyzer/boot_logo.h, plus simulator/boot_logo.png (the same
image at 2x) so the browser simulator shows exactly what the display will.
Transparent areas become black. The logo is scaled to fit inside a circle of
--diameter pixels, centred, so its edge isn't hidden under the bezel.
"""
import argparse
from pathlib import Path

from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
SIZE = 240


def render(src: Path, diameter: int, scale: int) -> Image.Image:
    logo = Image.open(src).convert("RGBA")
    bg = Image.new("RGBA", logo.size, (0, 0, 0, 255))
    flat = Image.alpha_composite(bg, logo).convert("RGB")
    d = diameter * scale
    flat = flat.resize((d, d), Image.LANCZOS)
    out = Image.new("RGB", (SIZE * scale, SIZE * scale), (0, 0, 0))
    off = (SIZE * scale - d) // 2
    out.paste(flat, (off, off))
    return out


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("png", type=Path)
    ap.add_argument("--diameter", type=int, default=232, help="logo size on the 240 px display (default 232)")
    args = ap.parse_args()

    img = render(args.png, args.diameter, 1)
    px = img.tobytes()
    words = [((px[i] & 0xF8) << 8) | ((px[i + 1] & 0xFC) << 3) | (px[i + 2] >> 3) for i in range(0, len(px), 3)]

    lines = [", ".join(f"0x{w:04X}" for w in words[i:i + 16]) + "," for i in range(0, len(words), 16)]
    header = ROOT / "firmware/O2_Analyzer/boot_logo.h"
    header.write_text(
        "// Generated by firmware/tools/png2rgb565.py from " + args.png.name + " -- do not edit by hand.\n"
        "#pragma once\n#include <stdint.h>\n\n"
        f"#define BOOT_LOGO_W {SIZE}\n#define BOOT_LOGO_H {SIZE}\n\n"
        "static const uint16_t BOOT_LOGO[BOOT_LOGO_W * BOOT_LOGO_H] = {\n  " + "\n  ".join(lines) + "\n};\n"
    )
    render(args.png, args.diameter, 2).save(ROOT / "simulator/boot_logo.png", optimize=True)
    print(f"wrote {header.relative_to(ROOT)} ({len(words) * 2} bytes of pixels) and simulator/boot_logo.png")


if __name__ == "__main__":
    main()
